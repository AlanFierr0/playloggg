import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createIgdbClient } from "./igdb-client.mjs";

const command = process.argv[2];
const readJson = async (path) => JSON.parse(await readFile(path, "utf8"));
const writeJson = async (path, value) => writeFile(path, JSON.stringify(value, null, 2) + "\n");
const snapshotPath = "supabase/igdb-games.json";
const sqlPath = "supabase/import-igdb.sql";

function validateMatches(matches, games) {
  if (matches.length !== games.length || new Set(matches.map((m) => m.slug)).size !== matches.length || new Set(matches.map((m) => m.igdbId)).size !== matches.length) throw new Error("Expected exactly one distinct IGDB match per existing game.");
  for (const match of matches) {
    if (!games.some((g) => g.slug === match.slug) || !Number.isSafeInteger(match.igdbId) || match.igdbId <= 0) throw new Error("Invalid reviewed IGDB match.");
  }
}

const sqlText = (value) => value === null ? "null" : `'${String(value).replaceAll("'", "''")}'`;
const sqlArray = (values) => `array[${values.map(sqlText).join(",")}]::text[]`;
const imageIds = (images = []) => images.map((image) => image.image_id).filter((id) => typeof id === "string" && /^[A-Za-z0-9_]+$/.test(id));

function importSql(snapshot) {
  const statements = snapshot.games.map((game) => `update public.games set
  igdb_id = ${game.igdb_id}, title = ${sqlText(game.title)},
  cover_url = ${sqlText(game.cover_url)}, cover_image_id = ${sqlText(game.cover_image_id)},
  released_on = ${sqlText(game.released_on)}, release_year = ${game.released_on ? Number(game.released_on.slice(0, 4)) : "null"},
  genres = ${sqlArray(game.genres)}, artwork_image_ids = ${sqlArray(game.artwork_image_ids)}, screenshot_image_ids = ${sqlArray(game.screenshot_image_ids)},
  igdb_url = ${sqlText(game.igdb_url)}, igdb_metadata = ${sqlText(JSON.stringify(game.igdb_metadata))}::jsonb,
  search_keywords = ${sqlText([game.title, game.slug.replaceAll("-", " "), ...game.genres].join(" "))},
  igdb_synced_at = ${sqlText(snapshot.fetchedAt)}::timestamptz, updated_at = ${sqlText(snapshot.fetchedAt)}::timestamptz
where slug = ${sqlText(game.slug)} and is_sample and (igdb_id is null or igdb_id = ${game.igdb_id});
`);
  const slugs = sqlArray(snapshot.games.map((game) => game.slug));
  return `-- Generated by scripts/igdb-catalog.mjs sql from a reviewed, versioned IGDB snapshot.
-- Administrative import only. Does not insert games, alter slugs or touch ratings/profiles.
begin;
do $$ begin
  if (select count(*) from public.games where slug = any(${slugs}) and is_sample) <> ${snapshot.games.length} then
    raise exception 'Import requires all reviewed sample games to exist; refusing partial import';
  end if;
end $$;
${statements.join("\n")}
do $$ begin
  if exists (select 1 from public.games where slug = any(${slugs}) and (igdb_id is null or igdb_synced_at is distinct from ${sqlText(snapshot.fetchedAt)}::timestamptz)) then
    raise exception 'An IGDB mapping changed; review it before importing';
  end if;
end $$;
commit;
`;
}

async function main() {
  const games = await readJson("src/data/games.json");
  if (command === "sql" || command === "check") {
    const snapshot = await readJson(snapshotPath);
    const matches = await readJson("supabase/igdb-matches.json");
    validateMatches(matches, games);
    if (snapshot.games.length !== matches.length || !snapshot.games.every((g) => matches.some((m) => m.slug === g.slug && m.igdbId === g.igdb_id))) throw new Error("Snapshot does not match the reviewed catalog.");
    const sql = importSql(snapshot);
    if (command === "check") {
      if (await readFile(sqlPath, "utf8") !== sql) throw new Error("Import SQL is out of date. Run the sql command.");
      console.log("Reviewed matches, IGDB snapshot and import SQL agree.");
    } else { await writeFile(sqlPath, sql); console.log(`Prepared ${snapshot.games.length} game updates in ${sqlPath}. No database writes performed.`); }
    return;
  }
  if (command !== "candidates" && command !== "fetch") throw new Error("Usage: node --env-file=.env.local scripts/igdb-catalog.mjs candidates|fetch|sql|check");
  const query = createIgdbClient();
  if (command === "fetch") {
    const matches = await readJson("supabase/igdb-matches.json");
    validateMatches(matches, games);
    const records = await query(`fields id,name,first_release_date,cover.image_id,genres.id,genres.name,platforms.id,platforms.name,involved_companies.company.id,involved_companies.company.name,involved_companies.developer,involved_companies.publisher,summary,artworks.image_id,screenshots.image_id,url,game_type.type; where id = (${matches.map((m) => m.igdbId).join(",")}); limit 100;`);
    const normalized = matches.map((match) => {
      const record = records.find((r) => r.id === match.igdbId);
      if (!record || !/^[A-Za-z0-9_]+$/.test(record.cover?.image_id ?? "")) throw new Error(`Missing game or valid cover for ${match.slug}.`);
      const companies = record.involved_companies ?? [];
      return {
        slug: match.slug, igdb_id: record.id, title: record.name,
        released_on: record.first_release_date ? new Date(record.first_release_date * 1000).toISOString().slice(0, 10) : null,
        genres: (record.genres ?? []).map((genre) => genre.name),
        cover_image_id: record.cover.image_id,
        cover_url: `https://images.igdb.com/igdb/image/upload/t_cover_big_2x/${record.cover.image_id}.jpg`,
        artwork_image_ids: imageIds(record.artworks), screenshot_image_ids: imageIds(record.screenshots),
        igdb_url: record.url ?? null,
        igdb_metadata: {
          genres: record.genres ?? [], platforms: record.platforms ?? [],
          developers: companies.filter((company) => company.developer).map((company) => company.company),
          publishers: companies.filter((company) => company.publisher).map((company) => company.company),
          summary: record.summary ?? null, game_type: record.game_type?.type ?? null,
        },
      };
    });
    await writeJson(snapshotPath, { fetchedAt: new Date().toISOString(), games: normalized });
    console.log(`Fetched ${normalized.length} reviewed games. No database writes performed.`);
    return;
  }
  const results = [];
  for (const game of games) {
    // Slugs expand abbreviated Stitch labels (e.g. Zelda: TotK).
    const search = game.slug.replaceAll("-", " ");
    const candidates = await query(`search ${JSON.stringify(search)}; fields id,name,slug,first_release_date,game_type.type,version_parent.name,cover.image_id,url; limit 20;`);
    results.push({ slug: game.slug, originalTitle: game.title, originalYear: game.year, candidates });
    console.log(`${game.slug}: ${candidates.length} candidates`);
  }
  await mkdir(".igdb", { recursive: true });
  await writeJson(".igdb/candidates.json", results);
}

main().catch((error) => { console.error(error instanceof Error ? error.message : "IGDB import failed."); process.exitCode = 1; });
